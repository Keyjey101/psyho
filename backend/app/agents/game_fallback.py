# Simple keyword→topic hints used by FallbackAnalyzer
_TOPIC_HINTS: dict[str, list[str]] = {
    "anxiety": ["тревог", "беспокой", "страх", "нервн", "волну"],
    "depression": ["грусть", "тоск", "нет сил", "нет смысла", "пусто"],
    "self_criticism": ["облажал", "ошибс", "виноват", "плохо справляюсь", "не справляюсь"],
    "burnout": ["устал", "выгорел", "нет энергии", "изможд", "истощ"],
    "relationships": ["отношени", "партнёр", "близк", "конфликт", "ссор"],
    "loneliness": ["одинок", "никому", "не нужен", "один"],
    "identity": ["кто я", "смысл", "не понимаю себя", "потерялся"],
    "procrastination": ["откладываю", "не могу начать", "завтра", "никак не собер"],
}


class FallbackAnalyzer:
    """Simple keyword-based analyzer used when LLM is unavailable."""

    def analyze_answers(self, answers: list[dict]) -> dict:
        scores: dict[str, int] = {topic: 0 for topic in _TOPIC_HINTS}
        text = " ".join(
            (a.get("choice_text") or "") + " " + (a.get("question") or "")
            for a in answers
        ).lower()
        for topic, keywords in _TOPIC_HINTS.items():
            for kw in keywords:
                if kw in text:
                    scores[topic] += 1

        if not any(scores.values()):
            # Random fallback
            dominant = random.choice(list(_TOPIC_HINTS.keys()))
        else:
            dominant = max(scores, key=lambda t: scores[t])

        total = sum(scores.values()) or 1
        top_score = scores[dominant]
        confidence = min(top_score / total + 0.1, 0.95)

        probabilities = {
            t: round(s / total, 2) for t, s in scores.items()
        }

        return {
            "probabilities": probabilities,
            "dominant_topic": dominant,
            "confidence": round(confidence, 2),
            "ready": confidence >= 0.80,
            "reasoning": "Анализ на основе паттернов ответов (резервный режим).",
        }


def get_fallback_question(used_indices: list[int]) -> dict:
    """Return a fallback question that hasn't been used yet (by index)."""
    available = [
        i for i in range(len(FALLBACK_QUESTIONS)) if i not in used_indices
    ]
    if not available:
        # All used — pick random
        idx = random.randrange(len(FALLBACK_QUESTIONS))
    else:
        idx = random.choice(available)
    return {"index": idx, **FALLBACK_QUESTIONS[idx]}
